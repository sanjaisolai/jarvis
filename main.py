import asyncio
import json

import websockets
from websockets.server import ServerConnection

from graph.graph import graph
from memory.manager import process_memory


HOST = "127.0.0.1"
PORT = 8765

USER_ID = "user_123"


UI_EVENT_TYPES = {
    "ui.create",
    "ui.update",
    "ui.remove",
    "ui.clear",
}


async def send_json(
    websocket: ServerConnection,
    data: dict,
):
    await websocket.send(
        json.dumps(data)
    )


async def process_chat(
    websocket: ServerConnection,
    message: dict,
):
    request_id = message["id"]
    user_input = message["content"]

    config = {
        "configurable": {
            "thread_id": USER_ID
        }
    }

    # Tell frontend that processing has started.
    await send_json(
        websocket,
        {
            "type": "chat.start",
            "id": request_id,
        },
    )

    full_response = ""

    try:

        async for event in graph.astream_events(
            {
                "messages": [
                    {
                        "role": "user",
                        "content": user_input,
                    }
                ]
            },
            config=config,
            version="v2",
        ):

            event_type = event["event"]

            # ==================================================
            # CHAT STREAM
            # ==================================================

            if event_type == "on_chat_model_stream":

                chunk = event["data"]["chunk"]

                content = chunk.content

                if not content:
                    continue

                # Some providers may return non-string content.
                if not isinstance(content, str):
                    continue

                # ----------------------------------------------
                # IMPORTANT
                #
                # Only stream the actual Jarvis response.
                # Do NOT stream tokens generated by sub-agents.
                # ----------------------------------------------

                metadata = event.get("metadata", {})

                node_name = metadata.get(
                    "langgraph_node"
                )

                if node_name != "jarvis":
                    continue

                full_response += content

                await send_json(
                    websocket,
                    {
                        "type": "chat.chunk",
                        "id": request_id,
                        "content": content,
                    },
                )

            # ==================================================
            # TOOL RESULT
            # ==================================================

            elif event_type == "on_tool_end":

                tool_name = event.get("name")

                # Only inspect the UI subagent tool.
                if tool_name != "ui_subagent_tool":
                    continue

                output = event["data"].get("output")

                if output is None:
                    continue

                # ----------------------------------------------
                # UI TOOL RESULT
                # ----------------------------------------------

                content = output.content
                try:
                    content_json = json.loads(content)
                except json.JSONDecodeError:
                    print("ui subagent returned invalid json")
                    continue

                if content_json.get("type") in UI_EVENT_TYPES:
                    print('sending ui events', content_json)

                    await send_json(
                        websocket,
                        content_json
                    )


        # ======================================================
        # CHAT END
        # ======================================================

        await send_json(
            websocket,
            {
                "type": "chat.end",
                "id": request_id,
            },
        )

        # ======================================================
        # LONG-TERM MEMORY
        # ======================================================

        conversation = [
            {
                "role": "user",
                "content": user_input,
            },
            {
                "role": "assistant",
                "content": full_response,
            },
        ]

        process_result = await process_memory(
            user_id=USER_ID,
            conversation=conversation,
        )


    except Exception as error:

        print(
            "Error processing message:",
            error,
        )

        await send_json(
            websocket,
            {
                "type": "chat.error",
                "id": request_id,
                "error": str(error),
            },
        )


async def handle_client(
    websocket: ServerConnection,
):

    print("Jarvis UI connected")

    try:

        async for raw_message in websocket:

            print(
                "Received:",
                raw_message,
            )

            try:

                message = json.loads(
                    raw_message
                )

            except json.JSONDecodeError:

                await send_json(
                    websocket,
                    {
                        "type": "chat.error",
                        "error": "Invalid JSON",
                    },
                )

                continue

            if message.get("type") == "chat.message":

                await process_chat(
                    websocket,
                    message,
                )

    except websockets.exceptions.ConnectionClosed:

        print(
            "Jarvis UI disconnected"
        )


async def main():

    print(
        f"Starting Jarvis WebSocket server "
        f"on ws://{HOST}:{PORT}"
    )

    async with websockets.serve(
        handle_client,
        HOST,
        PORT,
    ):

        print(
            "WebSocket server running..."
        )

        await asyncio.Future()


if __name__ == "__main__":
    asyncio.run(main())